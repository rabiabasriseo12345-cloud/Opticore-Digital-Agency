-- 1. Table: contact_inquiries
CREATE TABLE IF NOT EXISTS contact_inquiries (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  email TEXT NOT NULL,
  phone TEXT DEFAULT 'N/A',
  service TEXT DEFAULT 'SEO Services',
  budget TEXT DEFAULT 'Flexible',
  message TEXT NOT NULL,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 2. Table: quote_requests
CREATE TABLE IF NOT EXISTS quote_requests (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  email TEXT NOT NULL,
  phone TEXT DEFAULT 'N/A',
  company TEXT DEFAULT 'N/A',
  services JSONB DEFAULT '[]'::jsonb,
  monthly_budget TEXT DEFAULT 'Not specified',
  timeframe TEXT DEFAULT 'Immediately',
  notes TEXT DEFAULT '',
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- Enable Row Level Security (RLS)
ALTER TABLE contact_inquiries ENABLE ROW LEVEL SECURITY;
ALTER TABLE quote_requests ENABLE ROW LEVEL SECURITY;

-- Allow public inserts for forms
CREATE POLICY "Allow public insert on contact_inquiries" 
  ON contact_inquiries FOR INSERT WITH CHECK (true);

CREATE POLICY "Allow public insert on quote_requests" 
  ON quote_requests FOR INSERT WITH CHECK (true);

-- Allow public read for viewing inquiries in class demo
CREATE POLICY "Allow public select on contact_inquiries" 
  ON contact_inquiries FOR SELECT USING (true);

CREATE POLICY "Allow public select on quote_requests" 
  ON quote_requests FOR SELECT USING (true);
